"""Independent Python recipe for correlated SELECT and inverse aggregates."""
from asqueel import SqlBuilder


def subquery_model():
    builder = SqlBuilder()
    pkg = builder.source.db('subqueries', implementation='sqlite').packages().package('sq')
    customer = pkg.table('customer', pkey='id', order_by='$id')
    customer.column('id', dtype='L')
    customer.column('name', dtype='T')
    customer.formulaColumn('threshold', dtype='R', sql_formula='$id * :factor', var_factor=15)
    customer.formulaColumn('total', dtype='R', select=dict(table='sq.invoice', columns='SUM($amount)', where='$customer_id=#THIS.id'))
    customer.formulaColumn('has_big', dtype='B', exists=dict(table='sq.invoice', where='$customer_id=#THIS.id AND $amount>:minimum'), var_minimum=25)
    customer.formulaColumn('big_total', dtype='B', sql_formula='#found AND #sum > :limit', var_limit=40,
                           exists_found=dict(table='sq.invoice', where='$customer_id=#THIS.id AND $amount>25'),
                           select_sum=dict(table='sq.invoice', columns='SUM($amount)', where='$customer_id=#THIS.id'))
    customer.formulaColumn('local_total', dtype='R', var_minimum=10,
                           select=dict(table='sq.invoice', columns='SUM($adjusted)', where='$customer_id=#THIS.id AND $amount>:minimum', sqlparams=dict(minimum=15)))
    customer.formulaColumn('visible_total', dtype='R', select=dict(table='sq.invoice', columns='SUM($amount)', where='$customer_id=#THIS.id', excludeDraft=True, excludeLogicalDeleted=True, ignorePartition=False))
    customer.formulaColumn('first_code', dtype='T', select=dict(table='sq.invoice', columns='$code', where='$customer_id=#THIS.id', order_by='$id DESC', limit=1, offset=1, cast='TEXT'))
    customer.formulaColumn('nested_total', dtype='R', select=dict(table='sq.invoice', columns='SUM($tax_rate)', where='$customer_id=#THIS.id'))
    customer.formulaColumn('twice_total', dtype='R', sql_formula='$total * 2')
    customer.formulaColumn('above_threshold', dtype='R', select=dict(table='sq.invoice', columns='SUM($amount)', where='$customer_id=#THIS.id AND $amount>#THIS.threshold'))
    customer.formulaColumn('env_total', dtype='R', select=dict(table='sq.invoice', columns='SUM($amount)', where='$customer_id=#THIS.id AND $amount>:env_minimum'))
    customer.formulaColumn('field_parameter', dtype='R', select=dict(table='sq.invoice', columns='SUM($amount)', where='$customer_id=#THIS.id AND $amount>:threshold', sqlparams=dict(threshold='$qty')))
    customer.formulaColumn('multi_scalar', select=dict(table='sq.invoice', columns='$id,$amount', where='$customer_id=#THIS.id'))
    customer.formulaColumn('cast_exists', exists=dict(table='sq.invoice', where='$customer_id=#THIS.id', cast='TEXT'))
    customer.formulaColumn('conflicting_options', select=dict(table='sq.invoice', columns='$id', where='$customer_id=#THIS.id', excludeDraft=True, exclude_draft=False))
    customer.formulaColumn('unknown_option', select=dict(table='sq.invoice', columns='$id', where='$customer_id=#THIS.id', arbitrary=True))
    customer.formulaColumn('recursive', select=dict(table='sq.customer', columns='$recursive', where='$id=#THIS.id'))
    customer.subQueryColumn('legacy_json', query=dict(table='sq.invoice', columns='$id', where='$customer_id=#THIS.id'), mode='json')
    customer.subQueryColumn('method_query', query='unregistered')
    source = dict(table='sq.invoice', where='$customer_id=#THIS.id')
    customer.subQueryColumn('sub_count', dtype='L', query=source, aggr='count()')
    customer.subQueryColumn('sub_codes', dtype='T', query=dict(source, order_by='$id DESC'), aggr="join($code, ',', '-')")
    customer.subQueryColumn('sub_json', dtype='T', query=dict(source, order_by='$id'), aggr='to_json($id,$amount)')
    customer.subQueryColumn('scalar_max', dtype='R', query=dict(source, columns='MAX($amount)'))
    customer.virtualRelation('large', relation='@invoices', condition='$amount>:var_limit', var_limit='$threshold')
    customer.virtualRelation('window', relation='@large', condition='$amount<:var_limit', var_limit='$id * 35')
    customer.virtualRelation('direct', table='sq.invoice', condition='$customer_id=:var_customer AND $qty>:var_min', var_customer='$id', var_min='$id - 1')
    customer.virtualRelation('asking', relation='@invoices', ask=dict(fields=[dict(name='minimum', dtype='R')]))
    customer.virtualRelation('cycle_a', relation='@cycle_b')
    customer.virtualRelation('cycle_b', relation='@cycle_a')
    vat = pkg.table('vat', pkey='id')
    vat.column('id', dtype='L')
    vat.column('rate', dtype='R')
    invoice = pkg.table('invoice', pkey='id', order_by='$id', draftField='draft', logicalDeletionField='deleted', partition_region='region')
    invoice.column('id', dtype='L')
    invoice.column('customer_id', dtype='L').relation('customer.id', relation_name='invoices')
    invoice.column('vat_id', dtype='L').relation('vat.id')
    invoice.column('amount', dtype='R', sqlname='stored_amount')
    invoice.column('qty', dtype='L')
    invoice.column('code', dtype='T')
    invoice.column('draft', dtype='B')
    invoice.column('deleted', dtype='T')
    invoice.column('region', dtype='T')
    invoice.formulaColumn('adjusted', dtype='R', sql_formula='$amount + :offset', var_offset=5)
    invoice.formulaColumn('tax_rate', dtype='R', select=dict(table='sq.vat', columns='$rate', where='$id=#THIS.vat_id'))
    pair = pkg.table('pair', pkey='key')
    pair.column('code', dtype='T')
    pair.column('seq', dtype='L')
    pair.compositeColumn('key', columns='code,seq')
    member = pkg.table('member', pkey='id')
    member.column('id', dtype='L')
    member.column('code', dtype='T')
    member.column('seq', dtype='L')
    member.column('amount', dtype='R')
    member.compositeColumn('pair_key', columns='code,seq').relation('pair.key', relation_name='members')
    return builder
